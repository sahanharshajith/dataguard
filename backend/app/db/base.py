"""Shared SQLAlchemy base class, naming convention, and column mixins."""

from datetime import datetime
from typing import Any

from sqlalchemy import BigInteger, DateTime, Identity, MetaData, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Naming convention for database constraints and indexes, applied to every `Table` object.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_N_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    # Python type -> database type, applied to every `Mapped[...]` annotation.
    type_annotation_map = {
        datetime: DateTime(timezone=True),  # decision DB2: always timezone-aware
        dict[str, Any]: JSONB,              # decision DB4: flexible parameters
    }


class PrimaryKeyMixin:
    """`id BIGINT GENERATED BY DEFAULT AS IDENTITY` (decision DB1)."""

    id: Mapped[int] = mapped_column(
        BigInteger, Identity(), primary_key=True, sort_order=-1000
    )


class TimestampMixin:
    """`created_at` and `updated_at`, maintained by the database clock."""

    created_at: Mapped[datetime] = mapped_column(server_default=func.now(), sort_order=1000)
    updated_at: Mapped[datetime] = mapped_column(
        server_default=func.now(), onupdate=func.now(), sort_order=1001
    )