"""
Checks the database definition of the dataset tables, without needing a database.
"""

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateTable

import app.models  # noqa: F401  (registers the models)
from app.db.base import Base
from app.models.enums import Layer


def ddl(table_name: str) -> str:
    table = Base.metadata.tables[table_name]
    return str(CreateTable(table).compile(dialect=postgresql.dialect()))


def test_models_are_registered():
    assert {"datasets", "dataset_monitoring_config"} <= set(Base.metadata.tables)


def test_primary_key_is_bigint_identity():
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY" in ddl("datasets")


def test_timestamps_are_timezone_aware():
    assert "created_at TIMESTAMP WITH TIME ZONE" in ddl("datasets")


def test_layer_check_constraint_lists_every_enum_value():
    sql = ddl("datasets")
    assert "ck_datasets_layer_valid" in sql
    for layer in Layer:
        assert f"'{layer.value}'" in sql


def test_layer_and_name_are_unique_together():
    assert "uq_datasets_layer_name" in ddl("datasets")


def test_freshness_threshold_cannot_be_below_expected_refresh():
    sql = ddl("dataset_monitoring_config")
    assert "freshness_threshold_minutes >= expected_refresh_minutes" in sql


def test_config_row_is_deleted_with_its_dataset():
    assert "ON DELETE CASCADE" in ddl("dataset_monitoring_config")